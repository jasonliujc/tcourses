class Semester:
    def __init__(self, now: datetime, stage: int = 0):
        self.now = now
        self.stage = stage
        # 带夏令时的本机时区：固定偏移的话，跨过夏令时切换的截止会差一小时
        self.local = tz.tzlocal()
        self.problem_sets: list[tuple[int, datetime]] = []
        today = now.astimezone(self.local).date()
        monday = today - timedelta(days=today.weekday())
        self.term_start = monday - timedelta(weeks=CURRENT_WEEK - 1)
        self.term = _term_name(self.term_start)
        self.courses: dict[int, Course] = {}
        self.files: dict[int, DemoFile] = {}
        self.planner: list[dict] = []
        self.conversations: list[dict] = []
        self._ids: dict[str, int] = {}
        self._build()

    # ---------- 小工具 ----------

    def _id(self, space: str) -> int:
        start = {
            "file": 500_000,
            "page": 600_000,
            "assignment": 700_000,
            "quiz": 800_000,
            "topic": 900_000,
            "event": 950_000,
            "module": 1_000_000,
            "item": 1_100_000,
            "folder": 1_200_000,
            "note": 1_300_000,
            "conv": 1_400_000,
        }[space]
        self._ids[space] = self._ids.get(space, start) + 1
        return self._ids[space]

    def at(self, week: int, weekday: int, hh: int, mm: int = 0) -> datetime:
        """第 week 周的星期几（0=周一）几点，按本机时区。"""
        day = self.term_start + timedelta(weeks=week - 1, days=weekday)
        return datetime.combine(day, time(hh, mm), tzinfo=self.local)

    def url(self, path: str) -> str:
        return f"{BASE_URL}{path}"

    def _file(
        self, course: Course, name: str, folder: str | None, created: datetime, title: str = ""
    ) -> DemoFile:
        kind = name.rsplit(".", 1)[-1].lower()
        # 下周的题目按日历算是"明天"才发，但出现在今天的 Canvas 上就不能带着未来的时间
        if created > self.now:
            created = self.now - timedelta(days=1)
        f = DemoFile(self._id("file"), course.id, name, folder, created, kind, title)
        self.files[f.id] = f
        course.files.append(f.id)
        return f

    def file_json(self, f: DemoFile) -> dict:
        course = self.courses[f.course]
        size = len(file_bytes(f, course.name))
        folder_id = next(
            (x["id"] for x in course.folders if x["full_name"].endswith(f"/{f.folder}")), None
        )
        return {
            "id": f.id,
            "display_name": f.name,
            "filename": f.name.replace(" ", "_"),
            "content-type": CONTENT_TYPES.get(f.kind, "application/octet-stream"),
            "size": size,
            "url": self.url(f"/files/{f.id}/download?download_frd=1&verifier=demo"),
            "folder_id": folder_id if course.files_tab else None,
            "created_at": _iso(f.created),
            "updated_at": _iso(f.created),
            "modified_at": _iso(f.created),
            "locked": False,
            "hidden": False,
        }

    def _link(self, f: DemoFile) -> str:
        return (
            f'<a class="instructure_file_link" href="{BASE_URL}/courses/{f.course}/files/{f.id}'
            f'?wrap=1">{f.name}</a>'
        )

    @staticmethod
    def _ext(href: str, text: str) -> str:
        return f'<a href="{href}" target="_blank" rel="noopener">{text}</a>'

