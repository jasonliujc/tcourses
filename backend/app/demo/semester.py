def _pdf(lines: list[str]) -> bytes:
    """一页的合法 PDF，只用内置字体。演示里下载 / 打包下来的文件都能真的打开。"""

    def esc(s: str) -> str:
        s = s.encode("latin-1", "replace").decode("latin-1")
        return s.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")

    ops = ["BT", "/F1 22 Tf", "72 720 Td", f"({esc(lines[0])}) Tj", "/F1 12 Tf"]
    for line in lines[1:]:
        ops += ["0 -22 Td", f"({esc(line)}) Tj"]
    ops.append("ET")
    stream = "\n".join(ops).encode("latin-1")
    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
    ]
    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for i, body in enumerate(objects, 1):
        offsets.append(out.tell())
        out.write(f"{i} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = out.tell()
    out.write(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    for off in offsets:
        out.write(f"{off:010d} 00000 n \n".encode())
    out.write(
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode()
    )
    return out.getvalue()


def file_bytes(f: DemoFile, course_name: str) -> bytes:
    note = "Sample file generated by TCourses demo mode."
    if f.kind == "pdf":
        return _pdf([f.title or f.name.rsplit(".", 1)[0], course_name, "", note])
    if f.kind == "ipynb":
        nb = {
            "nbformat": 4,
            "nbformat_minor": 5,
            "metadata": {},
            "cells": [
                {
                    "cell_type": "markdown",
                    "metadata": {},
                    "source": [f"# {f.title or f.name}\n", note],
                },
                {
                    "cell_type": "code",
                    "metadata": {},
                    "execution_count": None,
                    "outputs": [],
                    "source": [
                        "import numpy as np\n",
                        "rng = np.random.default_rng(0)\n",
                        "rng.normal(size=5)",
                    ],
                },
            ],
        }
        return json.dumps(nb, indent=1).encode()
    if f.kind == "csv":
        rows = ["id,x1,x2,y"] + [
            f"{i},{i * 1.5:.1f},{(i * 7) % 11},{i * 2.1 + 3:.1f}" for i in range(1, 41)
        ]
        return ("\n".join(rows) + "\n").encode()
    if f.kind == "sql":
        return (
            f"-- {f.name}\n-- {note}\nCREATE TABLE student (\n  id INTEGER PRIMARY KEY,\n"
            "  name TEXT NOT NULL,\n  year INTEGER\n);\n"
        ).encode()
    if f.kind == "zip":
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
            z.writestr("README.md", f"# {f.name}\n\n{note}\n")
            z.writestr(
                "main.py",
                "def main():\n    print('hello')\n\n\nif __name__ == '__main__':\n    main()\n",
            )
        return buf.getvalue()
    return f"{f.name}\n{note}\n".encode()


