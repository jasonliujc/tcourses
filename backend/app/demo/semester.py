    def _common_events(self, course: Course) -> None:
        mid = self.at(7, 3, 18)
        self._event(
            course,
            f"{course.code} Midterm",
            mid,
            mid + timedelta(hours=2),
            location="Exam Centre, Hall B",
        )
        final = self.at(TOTAL_WEEKS + 2, course.id % 4, 9)
        self._event(
            course,
            f"{course.code} Final Exam",
            final,
            final + timedelta(hours=3),
            location="Main Gym",
        )
        if course.id not in (41001, 41003):
            return
        series = f"oh-{course.id}"
        day = course.id % 3
        for week in range(1, TOTAL_WEEKS + 1):
            start = self.at(week, day + 1, 15)
            self._event(
                course,
                "Office Hours",
                start,
                start + timedelta(hours=1),
                location=f"Room {200 + course.id % 100}",
                series=series,
                rrule=f"FREQ=WEEKLY;COUNT={TOTAL_WEEKS}",
            )

    def _weekly(self, course: Course, files_per_week, overview: bool = True) -> None:
        """每周一个模块：讲义（+ 阅读材料）挂在模块下，周概览页里再链一遍。"""
        for week in range(1, CURRENT_WEEK + 1):
            if course.topics[week - 1] == "Midterm":
                continue
            module = self._module(course, week)
            made = files_per_week(week)
            for f in made:
                self._item(course, module, "File", f.name, content_id=f.id)
            if overview:
                slug = f"week-{week}-overview"
                body = (
                    f"<h2>Week {week}: {course.topics[week - 1]}</h2>"
                    f"<p>Materials for this week:</p><ul>"
                    + "".join(f"<li>{self._link(f)}</li>" for f in made)
                    + "</ul>"
                )
                self._page(
                    course,
                    slug,
                    f"Week {week} Overview",
                    body,
                    made[0].created if made else self.at(week, 0, 8),
                )
                self._item(course, module, "Page", f"Week {week} Overview", page_url=slug)

