def _iso(dt: datetime) -> str:
    return dt.astimezone(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def _term_name(start: date) -> str:
    season = "Winter" if start.month <= 4 else "Summer" if start.month <= 8 else "Fall"
    return f"{season} {start.year}"


