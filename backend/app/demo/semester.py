    @property
    def active(self) -> list[Course]:
        return [c for c in self.courses.values() if not c.concluded]

    def _structure(self, course: Course) -> None:
        tab = lambda tid, label, hidden=False: {  # noqa: E731
            "id": tid,
            "label": label,
            "hidden": hidden,
            "type": "internal",
            "html_url": f"/courses/{course.id}/{tid}",
            "full_url": self.url(f"/courses/{course.id}/{tid}"),
        }
        course.tabs = [
            tab("home", "Home"),
            tab("announcements", "Announcements"),
            tab("syllabus", "Syllabus"),
            tab("modules", "Modules"),
            tab("assignments", "Assignments"),
            tab("quizzes", "Quizzes"),
            tab("files", "Files", hidden=not course.files_tab),
            tab("discussions", "Discussions"),
            tab("grades", "Grades"),
            tab("people", "People"),
        ]
        root = {"id": self._id("folder"), "full_name": "course files", "name": "course files"}
        course.folders = [root] + [
            {"id": self._id("folder"), "full_name": f"course files/{n}", "name": n}
            for n in ("Lectures", "Readings", "Assignments", "Exams", "Data")
        ]

    def _page(
        self,
        course: Course,
        slug: str,
        title: str,
        body: str,
        updated: datetime,
        front: bool = False,
    ) -> dict:
        page = {
            "page_id": self._id("page"),
            "url": slug,
            "title": title,
            "body": body,
            "updated_at": _iso(updated),
            "created_at": _iso(updated),
            "front_page": front,
            "html_url": self.url(f"/courses/{course.id}/pages/{slug}"),
            "published": True,
        }
        course.pages.append(page)
        if front:
            course.front_page = page
        return page

    def _module(self, course: Course, week: int) -> dict:
        module = {
            "id": self._id("module"),
            "name": f"Week {week}: {course.topics[week - 1]}",
            "position": week,
            "items": [],
        }
        course.modules.append(module)
        return module

    def _item(self, course: Course, module: dict, kind: str, title: str, **extra) -> None:
        item = {
            "id": self._id("item"),
            "title": title,
            "type": kind,
            "position": len(module["items"]) + 1,
            "html_url": self.url(f"/courses/{course.id}/modules/items/{self._ids['item']}"),
        }
        item.update(extra)
        module["items"].append(item)

    def _assignment(
        self,
        course: Course,
        name: str,
        week: int,
        body: str,
        points: int = 100,
        state: str = "auto",
    ) -> dict:
        due = self.at(week, 4, 23, 59)
        aid = self._id("assignment")
        a = {
            "id": aid,
            "name": name,
            "description": body,
            "due_at": _iso(due),
            "points_possible": points,
            "created_at": _iso(self.at(max(1, week - 2), 0, 9)),
            "updated_at": _iso(self.at(max(1, week - 2), 0, 9)),
            "submission_types": ["online_upload"],
            "html_url": self.url(f"/courses/{course.id}/assignments/{aid}"),
            "published": True,
        }
        course.assignments.append(a)
        past = due < self.now
        subs = {
            "submitted": past and state != "missing",
            "graded": past and state == "auto",
            "missing": state == "missing",
            "late": state == "late",
            "excused": False,
            "has_feedback": past and state == "auto",
        }
        self.planner.append(
            {
                "plannable_type": "assignment",
                "plannable_id": aid,
                "plannable_date": _iso(due),
                "course_id": course.id,
                "context_type": "Course",
                "html_url": f"/courses/{course.id}/assignments/{aid}",
                "new_activity": False,
                "plannable": {
                    "id": aid,
                    "title": name,
                    "due_at": _iso(due),
                    "points_possible": points,
                },
                "submissions": subs,
                "planner_override": None,
            }
        )
        return a

