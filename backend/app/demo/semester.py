    def _databases(self, c: Course) -> None:
        """Files 标签页开着、文件夹整齐的那种课。"""

        def week_files(week: int) -> list[DemoFile]:
            topic = c.topics[week - 1]
            out = [
                self._file(
                    c,
                    f"Lecture {week:02d} - {topic}.pdf",
                    "Lectures",
                    self.at(week, 0, 8),
                    title=f"Lecture {week}: {topic}",
                )
            ]
            if week % 2 == 1:
                out.append(
                    self._file(
                        c,
                        f"Reading - Chapter {week // 2 + 1}.pdf",
                        "Readings",
                        self.at(week, 0, 8, 30),
                    )
                )
            return out

        self._weekly(c, week_files)
        schema = self._file(c, "university_schema.sql", "Assignments", self.at(2, 2, 10))
        for n, week in enumerate((3, 6, 9, 12), 1):
            handout = self._file(
                c, f"Assignment {n} Handout.pdf", "Assignments", self.at(week - 2, 0, 9)
            )
            starter = self._file(c, f"a{n}_starter.zip", "Assignments", self.at(week - 2, 0, 9))
            extra = f"<li>{self._link(schema)}</li>" if n == 1 else ""
            self._assignment(
                c,
                f"Assignment {n}",
                week,
                "<p>Read the handout and submit your queries.</p>"
                f"<ul><li>{self._link(handout)}</li><li>{self._link(starter)}</li>{extra}</ul>",
                state="late" if n == 2 else "auto",
            )
        practice = self._file(c, "Midterm Practice.pdf", "Exams", self.at(6, 0, 9))
        solutions = self._file(c, "Midterm Practice Solutions.pdf", "Exams", self.at(6, 4, 9))
        for week in range(2, CURRENT_WEEK + 2):
            if c.topics[week - 1] != "Midterm":
                self._quiz(c, week)
        self._page(
            c,
            "course-information",
            "Course Information",
            "<h2>Welcome to CS 3200</h2><p>Lectures Tue/Thu 10:00. Useful references:</p><ul>"
            f"<li>{self._ext(PG_DOCS, 'PostgreSQL documentation')}</li>"
            f"<li>{self._ext(SQLITE_DOCS, 'SQLite SQL reference')}</li></ul>",
            self.at(1, 0, 8),
            front=True,
        )
        c.syllabus = (
            "<h2>Syllabus</h2><p>Grading: 4 assignments (40%), quizzes (10%), midterm (20%), "
            f"final (30%).</p><p>{self._ext(PG_DOCS + 'tutorial.html', 'PostgreSQL tutorial')}</p>"
        )
        self._announcement(
            c,
            "Welcome to CS 3200",
            "<p>Welcome! Lecture slides are posted every Monday.</p>",
            self.at(1, 0, 8),
        )
        self._announcement(
            c,
            "Midterm logistics",
            "<p>The midterm covers weeks 1-6. Practice exam attached.</p>",
            self.at(6, 0, 10),
            [practice],
        )
        self._announcement(
            c,
            "Practice solutions posted",
            f"<p>See {self._link(solutions)}.</p>",
            self.at(6, 4, 10),
        )

