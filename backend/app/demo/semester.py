    def _today(self) -> None:
        """ "今天"新出现的东西：演示启动时第二轮同步把它们变成「更新」和提醒。"""
        hours_ago = lambda h: self.now - timedelta(hours=h)  # noqa: E731
        db, stat, ml, la = (self.courses[i] for i in (41001, 41002, 41003, 41004))

        week = CURRENT_WEEK
        topic = db.topics[week - 1]
        slides = self._file(
            db,
            f"Lecture {week:02d} - {topic} (annotated).pdf",
            "Lectures",
            hours_ago(3),
            title=f"Lecture {week}: {topic} (annotated)",
        )
        module = next(m for m in db.modules if m["name"].startswith(f"Week {week}:"))
        self._item(db, module, "File", slides.name, content_id=slides.id)

        notes = self._file(stat, "insurance.csv", None, hours_ago(5))
        self._item(stat, stat.modules[-1], "File", notes.name, content_id=notes.id)

        n = max(k for k, due in self.problem_sets if due < self.now)
        sol = self._file(la, f"Problem Set {n} Solutions.pdf", "Assignments", hours_ago(2))
        self._announcement(
            la,
            f"Problem Set {n} solutions posted",
            "<p>Solutions are attached.</p>",
            hours_ago(2),
            [sol],
        )

        # 改了截止日期：同步会把它识别成"变动"而不是新东西
        hw = next(a for a in ml.assignments if a["name"] == "HW 4")
        clar = self._file(ml, "hw4_clarifications.pdf", None, hours_ago(4))
        new_due = datetime.fromisoformat(hw["due_at"].replace("Z", "+00:00")) + timedelta(days=2)
        hw["due_at"] = _iso(new_due)
        hw["updated_at"] = _iso(hours_ago(4))
        hw["description"] += f"<p>Deadline extended. See {self._link(clar)}.</p>"
        for p in self.planner:
            if p["plannable_type"] == "assignment" and p["plannable_id"] == hw["id"]:
                p["plannable"]["due_at"] = hw["due_at"]
                p["plannable_date"] = hw["due_at"]

        self.conversations.append(
            self._conversation(
                db, "Office hours moved to Thursday", "This week only, same room.", hours_ago(1)
            )
        )
